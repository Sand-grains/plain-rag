"""unit：benchmark 加载/校验/默认值填充（eval/core/benchmark.py）。"""
import json

import pytest

from eval.core import benchmark as benchmark_module
from eval.core.benchmark import load_benchmark, _auto_query_id


def _write(tmp_path, items):
    path = tmp_path / "bench.json"
    path.write_text(json.dumps(items, ensure_ascii=False), encoding="utf-8")
    return str(path)


class TestLoadBenchmark:
    def test_full_item_parsed(self, tmp_path):
        item = {
            "query_id": "Q1", "query": "q", "reference_facts": "rf", "source_doc": "doc",
            "category": "cat", "difficulty": "hard", "expected_parent_ids": ["p0"],
            "relevance": {"p0": 3}, "expected_files": ["a.md"], "expected_pages": ["1"],
            "expected_child_ids": ["p0:c0"],
        }
        result = load_benchmark(_write(tmp_path, [item]))
        loaded = result.valid_items[0]
        assert loaded.query_id == "Q1"
        assert loaded.query == "q"
        assert loaded.reference_facts == "rf"
        assert loaded.expected_parent_ids == ["p0"]
        assert loaded.relevance == {"p0": 3}
        assert loaded.expected_child_ids == ["p0:c0"]
        assert loaded.category == "cat"
        assert loaded.difficulty == "hard"

    def test_missing_query_id_autogenerated(self, tmp_path):
        result = load_benchmark(_write(tmp_path, [{"query": "a"}, {"query": "b"}]))
        assert [item.query_id for item in result.valid_items] == ["Q0001", "Q0002"]
        assert result.missing_query_id == [0, 1]

    def test_expected_chunk_ids_fallback(self, tmp_path):
        result = load_benchmark(_write(tmp_path, [{"expected_chunk_ids": ["p0", "p1"]}]))
        assert result.valid_items[0].expected_parent_ids == ["p0", "p1"]

    def test_ground_truth_fallback(self, tmp_path):
        result = load_benchmark(_write(tmp_path, [{"ground_truth": "gt"}]))
        assert result.valid_items[0].reference_facts == "gt"

    def test_missing_category_difficulty_default_unknown(self, tmp_path):
        result = load_benchmark(_write(tmp_path, [{"query": "q"}]))
        loaded = result.valid_items[0]
        assert loaded.category == "unknown"
        assert loaded.difficulty == "unknown"
        assert result.missing_category == [0]
        assert result.missing_difficulty == [0]

    def test_missing_relevance_defaults_to_three(self, tmp_path):
        result = load_benchmark(_write(tmp_path, [{"expected_parent_ids": ["p0", "p1"]}]))
        assert result.valid_items[0].relevance == {"p0": 3, "p1": 3}
        assert result.missing_relevance == [0]

    def test_invalid_chunk_ids_recorded(self, tmp_path):
        result = load_benchmark(
            _write(tmp_path, [{"expected_parent_ids": ["p0", "missing"]}]),
            valid_chunk_ids={"p0"},
        )
        assert result.invalid_chunk_ids == {0: ["missing"]}

    def test_missing_file_raises(self):
        with pytest.raises(FileNotFoundError):
            load_benchmark("definitely_missing_benchmark.json")

    def test_relative_path_resolves_from_project_root(self, tmp_path, monkeypatch):
        # _PROJECT_ROOT 被替换为 tmp_path → 相对路径 "benchmark/private.json" 解析到 tmp
        monkeypatch.setattr(benchmark_module, "_PROJECT_ROOT", tmp_path)
        target = tmp_path / "benchmark"
        target.mkdir()
        (target / "private.json").write_text(json.dumps([{"query_id": "Q9"}]), encoding="utf-8")
        result = load_benchmark("benchmark/private.json")
        assert result.valid_items[0].query_id == "Q9"


class TestAutoQueryId:
    def test_zero_index(self):
        assert _auto_query_id(0) == "Q0001"

    def test_ninth_index(self):
        assert _auto_query_id(9) == "Q0010"
